const { chromium } = require('playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1366, height: 900 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => { if (['warning', 'error'].includes(message.type())) console.log(message.type(), message.text()); });
    page.on('response', response => { if (response.url().includes('.glb')) console.log('MODEL HTTP:', response.status()); });
    await page.addInitScript(() => localStorage.setItem('cineva_token', 'browser-test'));
    const movies = JSON.parse(fs.readFileSync('backend/src/data/movies.json', 'utf8'));
    await page.route('**/api/**', route => route.fulfill({ json: route.request().url().endsWith('/auth/me') ? { id: 'qa', name: 'Test', role: 'user' } : route.request().url().endsWith('/movies') ? movies : [] }));
    await page.goto('http://127.0.0.1:5173/');
    await page.locator('footer').waitFor();
    await page.locator('.butterfly-flight[data-ready="true"]').waitFor({ timeout: 30000 });
    assert.equal(await page.locator('.cinema-bee').count(), 0);
    assert.equal(await page.locator('.butterfly-flight').evaluate(el => getComputedStyle(el).pointerEvents), 'none');
    await page.screenshot({ path: 'butterfly-check.png' });
    await page.getByRole('button', { name: 'Kapalaklarni yashirish' }).click();
    assert.equal(await page.locator('.butterfly-flight').count(), 0);
    await page.getByRole('button', { name: 'Kapalaklarni ko‘rsatish' }).click();
    await page.locator('.butterfly-flight[data-ready="true"]').waitFor({ timeout: 30000 });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.setViewportSize({ width: 1366, height: 900 });
    await page.getByRole('link', { name: '3D kutubxona · Biz haqimizda' }).click();
    await page.waitForURL('**/about');
    assert.equal(await page.locator('.butterfly-flight').count(), 0);
    await page.waitForFunction(() => document.querySelectorAll('.model-viewer[data-status="ready"]').length === 4, { timeout: 60000 });
    await page.locator('#models').scrollIntoViewIfNeeded();
    await page.screenshot({ path: 'bee-check.png' });
    assert.equal(await page.locator('canvas').count(), 4);
    const icon = await page.request.get('http://127.0.0.1:5173/favicon.png');
    assert.equal(icon.status(), 200);
    assert.match(icon.headers()['content-type'], /image\/png/);
    await page.getByRole('button', { name: 'Fantastik kapalak — ko‘rish' }).click();
    const dialog = page.getByRole('dialog');
    await dialog.locator('.model-viewer[data-status="ready"]').waitFor({ timeout: 30000 });
    await page.getByRole('button', { name: 'Animatsiyani to‘xtatish' }).click();
    await page.getByRole('button', { name: 'Animatsiyani yoqish' }).click();
    const canvas = dialog.locator('canvas');
    const rect = await canvas.boundingBox();
    await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2);
    await page.mouse.down(); await page.mouse.move(rect.x + rect.width / 2 + 80, rect.y + rect.height / 2 + 20); await page.mouse.up();
    await page.mouse.wheel(0, -100);
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('dialog').count(), 0);
    await page.getByRole('button', { name: 'Demon ari — ko‘rish' }).click();
    await page.getByRole('dialog').locator('.model-viewer[data-status="ready"]').waitFor({ timeout: 30000 });
    await page.getByRole('button', { name: 'Model oynasini yopish' }).click();
    for (const name of ['Kolibri', 'Feniks']) {
      await page.getByRole('button', { name: `${name} — ko‘rish` }).click();
      await page.getByRole('dialog').locator('.model-viewer[data-status="ready"]').waitFor({ timeout: 30000 });
      await page.getByRole('button', { name: 'Model oynasini yopish' }).click();
    }
    await page.setViewportSize({ width: 390, height: 844 });
    await page.evaluate(() => window.scrollTo(0, 800));
    await page.waitForTimeout(1500);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.getByRole('link', { name: 'Qo‘llab-quvvatlash', exact: true }).click();
    await page.waitForURL('**/about#support');
    await page.getByText('Hisobimga qanday kiraman?', { exact: true }).click();
    assert.equal(await page.locator('details').first().getAttribute('open'), '');
    assert.deepEqual(errors, []);
    console.log('PASS: home butterflies, four library models, all viewer dialogs, pause/play, rotate/zoom, Escape, mobile layout, support FAQ, no runtime errors.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
